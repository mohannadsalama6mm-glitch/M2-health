export const messages: Record<Locale, Record<MessageKey, string>> = { en, ar };

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "ar";
}

export function directionFor(locale: Locale): Direction {
  return locale === "ar" ? "rtl" : "ltr";
}

export function localeTag(locale: Locale): string {
  return locale === "ar" ? "ar-EG" : "en-GB";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`,
  );
}

export function formatNumber(
  locale: Locale,
  value: number,
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(localeTag(locale), options).format(value);
}

export function formatCurrencyMinor(locale: Locale, minor: number, currency = "EGP"): string {
  const amount = formatNumber(locale, minor / 100, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return locale === "ar" && currency === "EGP" ? `${amount} ج.م.` : `${amount} ${currency}`;
}

export function formatDate(locale: Locale, value: string | number | Date): string {
  return new Intl.DateTimeFormat(localeTag(locale), { dateStyle: "medium" }).format(new Date(value));
}

export function formatDateTime(locale: Locale, value: string | number | Date): string {
  return new Intl.DateTimeFormat(localeTag(locale), {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(value));
}

const stateKeys: Record<string, MessageKey> = {
  TRIAL: "state.trial",
  ACTIVE: "state.active",
  EXPIRED: "state.expired",
  SUSPENDED: "state.suspended",
  REVOKED: "state.revoked",
  PENDING: "state.pending",
  FULFILLED: "state.fulfilled",
  UNACTIVATED: "state.unactivated",
  OFFLINE_GRACE: "state.offlineGrace",
  READ_ONLY: "state.readOnly",
  CANCELLED: "state.cancelled",
  CANCELED: "state.cancelled",
  APPROVED: "state.approved",
  DENIED: "state.denied",
};

export function semanticStateKey(value: string): MessageKey {
  return stateKeys[value.trim().toUpperCase()] ?? "state.unknown";
}

export function localizeSemanticState(locale: Locale, value: string): string {
  return translate(locale, semanticStateKey(value));
}
